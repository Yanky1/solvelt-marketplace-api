#!/usr/bin/env python3
"""
Generates the Unicode normalisation tables of src/Solvelt.Marketplace.Api/Text/UnicodeNormalizationData.cs and the test vectors of
tests/Solvelt.Marketplace.Api.Tests/Data/normalization-vectors.txt (decision M1-81).

Why: the application runs with InvariantGlobalization (no ICU in the image), where string.Normalize() does nothing. The managed normaliser
(Text/UnicodeNormalizer.cs) needs the canonical decomposition and combining class data of one Unicode version. Run this with the Python whose
unicodedata is the Unicode version you want (the repository pins 15.1.0, the version of ICU 74 and .NET 9/10), then run
`dotnet run --project tools/NormalizationCheck` on a machine WITH ICU to compare the result with .NET's own normaliser.

The tables are derived, not copied: composition pairs are the two-character canonical decompositions whose NFC is the character itself
(which drops exactly the Full_Composition_Exclusion characters), so the exclusion list needs no separate file.
"""
import random
import sys
import unicodedata as u

EXPECTED = "15.1.0"
if u.unidata_version != EXPECTED:
    sys.exit(f"unicodedata is Unicode {u.unidata_version}, this generator is pinned to {EXPECTED}; change EXPECTED on purpose and regenerate everything")

MAX = 0x110000
HANGUL_S, HANGUL_E = 0xAC00, 0xD7A3

ccc = {}
one_step = {}
for cp in range(MAX):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    ch = chr(cp)
    c = u.combining(ch)
    if c:
        ccc[cp] = c
    d = u.decomposition(ch)
    if HANGUL_S <= cp <= HANGUL_E:
        continue   # Hangul syllables are decomposed and composed by arithmetic (UAX #15, section 'Hangul Syllable Decomposition'), not by table
    if d and not d.startswith("<"):
        one_step[cp] = [int(x, 16) for x in d.split()]


def full(cp):
    parts = one_step.get(cp)
    if parts is None:
        return [cp]
    out = []
    for p in parts:
        out.extend(full(p))
    return out


decomp = {cp: full(cp) for cp in one_step}
compose = {}
for cp, parts in one_step.items():
    if len(parts) == 2 and u.normalize("NFC", chr(cp)) == chr(cp) and not (0x1100 <= parts[0] <= 0x1112 and 0x1161 <= parts[1] <= 0x1175):
        compose[(parts[0], parts[1])] = cp

# ---- C# source
ranges = []
for cp in sorted(ccc):
    if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == ccc[cp]:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, ccc[cp]])


def ints(values, per_line=16, indent="        "):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append(indent + ", ".join(str(v) for v in values[i:i + per_line]))
    return ",\n".join(lines)


keys = sorted(decomp)
start, data = [], []
for k in keys:
    start.append(len(data))
    data.extend(decomp[k])
start.append(len(data))
pair_keys = sorted(compose)
packed = [(a << 21) | b for a, b in pair_keys]
results = [compose[p] for p in pair_keys]

src = f"""// <auto-generated>
// Generated by tools/unicode/generate_normalization.py from Python's unicodedata (Unicode {u.unidata_version}). Do not edit by hand; see decision M1-81.
// </auto-generated>
namespace Solvelt.Marketplace.Api.Text;

internal static class UnicodeNormalizationData
{{
    public const string UnicodeVersion = "{u.unidata_version}";

    /// <summary>Canonical combining classes as ranges: start, end, class (inclusive), sorted by start. Everything not listed is 0.</summary>
    public static readonly int[] CombiningClassRanges =
    [
{ints([x for r in ranges for x in r], 15)}
    ];

    /// <summary>Code points with a canonical decomposition, sorted. <see cref="DecompositionStart"/>[i]..[i+1] delimit the FULL canonical decomposition of key i in <see cref="DecompositionData"/>. Hangul syllables are algorithmic and not listed.</summary>
    public static readonly int[] DecompositionKeys =
    [
{ints(keys)}
    ];

    public static readonly int[] DecompositionStart =
    [
{ints(start)}
    ];

    public static readonly int[] DecompositionData =
    [
{ints(data)}
    ];

    /// <summary>Primary composites: (first &lt;&lt; 21 | second), sorted, with the composite in <see cref="CompositionResults"/>.</summary>
    public static readonly long[] CompositionPairs =
    [
{ints(packed, 8)}
    ];

    public static readonly int[] CompositionResults =
    [
{ints(results)}
    ];
}}
"""
open("src/Solvelt.Marketplace.Api/Text/UnicodeNormalizationData.cs", "w", encoding="utf-8").write(src)

# ---- test vectors: <code points>;<NFC>;<NFD>   (hex, space separated)
def hexs(s):
    return " ".join(f"{ord(c):X}" for c in s)


vectors = []
changed = 0
for cp in range(MAX):
    if 0xD800 <= cp <= 0xDFFF or HANGUL_S <= cp <= HANGUL_E:
        continue
    ch = chr(cp)
    nfc, nfd = u.normalize("NFC", ch), u.normalize("NFD", ch)
    if nfc != ch or nfd != ch:
        vectors.append(f"{hexs(ch)};{hexs(nfc)};{hexs(nfd)}")
        changed += 1

rng = random.Random(20260105)
starters = [c for c in range(0x20, 0x250) if u.combining(chr(c)) == 0 and u.category(chr(c))[0] in "LN"][:200]
starters += [0x391, 0x3B1, 0x410, 0x430, 0x5D0, 0x627, 0x915, 0xE01, 0x1100, 0x1161, 0x11A8, 0xAC00, 0xAC01, 0xD7A3, 0x3042, 0x30AB, 0x4E00, 0x212B, 0x2126, 0x1F00, 0x1F88, 0x0958, 0x0F40, 0x1B05]
marks = sorted(ccc)
marks = [m for m in marks if m < 0x10000][::3] + [0x300, 0x301, 0x302, 0x303, 0x308, 0x30A, 0x323, 0x327, 0x328, 0x31B, 0x345, 0x3099, 0x309A, 0x340, 0x341, 0x343, 0x344, 0x93C, 0xF71, 0xF72, 0xF74, 0xF80, 0x1D165, 0x1D16D]
pool = starters + marks + [0x1100, 0x1161, 0x11A8, 0x1112, 0x1175, 0x11C2, 0xAC00, 0xC800, 0x20, 0x41, 0x61, 0x1F600, 0x20000]
for _ in range(2500):
    n = rng.randint(1, 8)
    seq = "".join(chr(rng.choice(pool)) for _ in range(n))
    vectors.append(f"{hexs(seq)};{hexs(u.normalize('NFC', seq))};{hexs(u.normalize('NFD', seq))}")
# long runs of marks (canonical ordering of many)
for _ in range(150):
    seq = chr(rng.choice(starters)) + "".join(chr(rng.choice(marks)) for _ in range(rng.randint(2, 12)))
    vectors.append(f"{hexs(seq)};{hexs(u.normalize('NFC', seq))};{hexs(u.normalize('NFD', seq))}")

path = "tests/Solvelt.Marketplace.Api.Tests/Data/normalization-vectors.txt"
import os
os.makedirs(os.path.dirname(path), exist_ok=True)
open(path, "w", encoding="utf-8", newline="\n").write(f"# Unicode {u.unidata_version}: <code points>;<NFC>;<NFD>. Generated by tools/unicode/generate_normalization.py (decision M1-81).\n# The first {changed} lines are every single code point that changes under NFC or NFD; the rest are seeded random sequences.\n" + "\n".join(vectors) + "\n")
print(f"Unicode {u.unidata_version}: {len(ranges)} combining class ranges, {len(keys)} decompositions ({len(data)} code points), {len(pair_keys)} composition pairs, {changed} changing code points, {len(vectors)} vectors")
